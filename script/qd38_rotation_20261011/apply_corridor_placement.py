"""Build and audit the accepted offline corridor placement; preserve native CAD.

The source remains immutable. Component/pad/body transforms and DC endpoint
vias move together. Only source-based Top ZIF fanout remains routed; RF/DC
routes, masks and shielding must be regenerated by their respective stages.
"""
import copy,hashlib,json,math
from pathlib import Path
from shapely.affinity import rotate,translate
from shapely.geometry import Point,Polygon,box
from shapely.ops import unary_union
from build_rotated_placement import pg
from revision_invariants import assert_plan_contacts

HERE=Path(__file__).resolve().parent
SOURCE=HERE/"placement_candidate.json"
DEST=HERE/"placement_corridor_candidate.json"
TARGETS={"C11":(5.05,39.6,270.),"R11":(2.90000043,39.12143733,180.),
         "C30":(15.75,44.4,90.),"R30":(14.50000043,45.97856267,180.)}


def apply_contact_pool(p,source_hash):
    # Match the existing contact-pool builder, without overwriting its source
    # or output. Assignment is provisional and may be reordered by DC routing.
    selected=sorted(set(range(2,50,2))|set(range(1,28,2)))
    contacts=sorted([a for a in p["physical_pads"] if a["ref"]=="J1" and int(a["pin"]) in selected],key=lambda a:(a["x"],a["y"]))
    sources=sorted([v for v in p["vias"] if not v["label"].startswith("J1-")],key=lambda v:(v["x"],v["y"]))
    assert len(sources)==len(contacts)==38
    p["vias"]=sources;p["tracks"]=[];mapping={}
    for i,(v,a) in enumerate(zip(sources,contacts)):
        layer=2 if i<19 else 4
        pin=int(a["pin"]);net=v["net"];q=int(net[2:])
        v.update(assigned_dc_layer=layer,routing_layer=layer)
        via=dict(x=a["x"],y=a["y"]+(.55 if pin%2==0 else -.55),net=net,diameter=.4,hole=.2,low=1,high=32,
                 routing_layer=layer,assigned_dc_layer=layer,label=f"J1-{pin}")
        p["vias"].append(via);mapping[pin]=net
        p["tracks"].append(dict(net=net,layer=1,width=.15,a=[a["x"],a["y"]],b=[via["x"],via["y"]]))
        p["dc_endpoints"][str(q)].update(zif_pin=pin,layer=layer)
        next(row for row in p["pinmap"] if row["qd_pad"]==q).update(zif_pin=pin,dc_layer=layer)
        next(j for j in p["route_jobs"] if j["kind"]=="DC" and j["net"]==net).update(a=[via["x"],via["y"]],b=[v["x"],v["y"]],layer=layer)
    for a in p["physical_pads"]:
        if a["ref"]=="J1":a["net"]=mapping.get(int(a["pin"]))
    p["nets"]={}
    for a in p["physical_pads"]:
        if a["ref"] and a["net"]:p["nets"].setdefault(a["net"],[]).append(a["ref"]+"-"+a["pin"])
    p["user_confirmed_contact_pool"]=True
    p["contact_pool_policy"]=dict(legacy_even_pins=list(range(2,50,2)),added_odd_pins=list(range(1,28,2)),pin50_unused=True,
        function_mapping_free_within_pool=True,source_placement_sha256=source_hash)


def audit(p,old):
    failures=[];pads=p["physical_pads"];vias=p["vias"];pgs=[pg(d) for d in pads]
    def check(ok,kind,**detail):
        if not ok:failures.append(dict(kind=kind,**detail))
    allgaps=[];vgaps=[];holegaps=[];via_gaps=[]
    for i,a in enumerate(pads):
        if a["ref"]=="J1":continue
        for j in range(i+1,len(pads)):
            b=pads[j]
            if b["ref"]=="J1" or a["net"]==b["net"]:continue
            if a["layer"]!=b["layer"] and 74 not in (a["layer"],b["layer"]):continue
            gap=pgs[i].distance(pgs[j]);allgaps.append(gap)
            check(gap>=.15-1e-6,"foreign_pad_clearance",a=[a["ref"],a["pin"]],b=[b["ref"],b["pin"]],gap_mm=gap)
    for via in vias:
        for pad,geom in zip(pads,pgs):
            if via["net"]==pad["net"]:continue
            gap=Point(via["x"],via["y"]).distance(geom)-via["diameter"]/2;vgaps.append(gap)
            check(gap>=.15-1e-6,"via_foreign_pad_clearance",via=via["label"],pad=[pad["ref"],pad["pin"]],gap_mm=gap)
        if not via["label"].startswith("J1-"):
            ref,pin=via["label"].split("-");pad=next(d for d in pads if d["ref"]==ref and d["pin"]==pin)
            check(pg(pad).buffer(1e-7).covers(Point(via["x"],via["y"]).buffer(via["hole"]/2,quad_segs=128)),"endpoint_drill_not_in_pad",via=via["label"])
    for i,a in enumerate(vias):
        for b in vias[i+1:]:
            dist=math.dist([a["x"],a["y"]],[b["x"],b["y"]]);holegap=dist-(a["hole"]+b["hole"])/2;holegaps.append(holegap)
            check(holegap>=.254-1e-6,"via_drill_clearance",a=a["label"],b=b["label"],gap_mm=holegap)
            if a["net"]==b["net"]:continue
            gap=dist-(a["diameter"]+b["diameter"])/2;via_gaps.append(gap)
            check(gap>=.15-1e-6,"via_land_clearance",a=a["label"],b=b["label"],gap_mm=gap)
    bodies=[(b["ref"],Polygon(b["outline"])) for b in p["passive_bodies"]]
    bgap=min(a.distance(b) for i,(_,a) in enumerate(bodies) for _,b in bodies[i+1:]);check(bgap>=.254-1e-6,"body_body_clearance",gap_mm=bgap)
    body_hole_gap=math.inf
    for ref,geom in bodies:
        for d in pads:
            if not d["hole"]:continue
            gap=geom.distance(Point(d["x"],d["y"]).buffer(d["hole"]/2,quad_segs=128));body_hole_gap=min(body_hole_gap,gap)
            check(gap>=.254-1e-6,"body_hole_clearance",ref=ref,pad=[d["ref"],d["pin"]],gap_mm=gap)
    board=Polygon(p["board_outline"]).buffer(-.2)
    for d,g in zip(pads,pgs):
        if d["ref"] in TARGETS:check(board.covers(g),"moved_pad_edge_clearance",ref=d["ref"],pin=d["pin"])
    for field in ("pads","board_outline","sample_center","cavity_mm","stack","mounts"):
        check(p[field]==old[field],"immutable_source_geometry_changed",field=field)
    unchanged=lambda v:v["ref"] not in TARGETS and v["ref"]!="J1"
    check([v for v in pads if unchanged(v)]==[v for v in old["physical_pads"] if unchanged(v)],"non_target_physical_pad_changed")
    check(all(s["q"]==int(s["ref"][3:]) for s in p["smp"]),"nonidentity_RF_assignment")
    check(not any(v["net"].startswith(("S","MW")) for v in vias),"RF_signal_via")
    pool=assert_plan_contacts(p)
    return dict(passed=not failures,failures=failures,status="OFFLINE_CORRIDOR_STATIC_PLACEMENT_VALIDATED_NOT_ROUTED",
        component_count=len(p["components"]),physical_pad_count=len(pads),signal_via_count=len(vias),
        minimum_pad_gap_mm=min(allgaps),minimum_via_to_foreign_pad_mm=min(vgaps),minimum_via_land_gap_mm=min(via_gaps),
        minimum_via_drill_gap_mm=min(holegaps),minimum_passive_body_gap_mm=bgap,minimum_body_through_hole_gap_mm=body_hole_gap,
        exact_contact_pool=pool,identity_RF_mapping=True,native_modified=False,
        model_transform_convention="Native generator uses each updated component origin/rotation and source embedded STEP offsets; passive body outlines are transformed identically.",
        limitation="Static pad/via/drill/source-body outline checks only. RF/DC routing, surfaces, shield rings, native 3D solids and save/reopen DRC remain required.")


def main():
    raw=SOURCE.read_bytes();old=json.loads(raw);p=copy.deepcopy(old);source_hash=hashlib.sha256(raw).hexdigest()
    for ref,(nx,ny,rotation) in TARGETS.items():
        comp=next(c for c in p["components"] if c["ref"]==ref);ox,oy,angle=comp["x"],comp["y"],comp["rotation"]
        delta=(rotation-angle)%360
        def move(x,y):
            point=translate(rotate(Point(x,y),delta,origin=(ox,oy)),nx-ox,ny-oy)
            return point.x,point.y
        for pad in p["physical_pads"]:
            if pad["ref"]==ref:pad["x"],pad["y"]=move(pad["x"],pad["y"]);pad["rotation"]=(pad["rotation"]+delta)%360
        for body in p["passive_bodies"]:
            if body["ref"]==ref:body["outline"]=[list(move(x,y)) for x,y in body["outline"]]
        for via in p["vias"]:
            if via["label"].startswith(ref+"-"):via["x"],via["y"]=move(via["x"],via["y"])
        comp.update(x=nx,y=ny,rotation=rotation)
    pads={(a["ref"],a["pin"]):a for a in p["physical_pads"]}
    xy=lambda a:[a["x"],a["y"]]
    for group in sorted({int(ref[1:]) for ref in TARGETS}):
        c1,c2,r1,r2=[pads[ref,pin] for ref,pin in ((f"C{group:02}","1"),(f"C{group:02}","2"),(f"R{group:02}","1"),(f"R{group:02}","2"))]
        p["dc_endpoints"][str(group)].update(x=r2["x"],y=r2["y"])
        for job in p["route_jobs"]:
            if job["net"]==f"S{group:02}" and job["kind"]=="RF":job["b"]=xy(c1)
            elif job["net"]==f"MW{group:02}" and job["kind"]=="RF_BIAS":job.update(a=xy(c2),b=xy(r1))
            elif job["net"]==f"MW{group:02}" and job["kind"]=="RF_QD":job["b"]=xy(r1)
            elif job["net"]==f"DC{group:02}" and job["kind"]=="DC":job["b"]=xy(r2)
    for collection in (p["smp"],p["components"]):
        for comp in collection:
            if comp["ref"]=="SMP30":comp["escape_angle_deg"]=90.
            if comp["ref"]=="SMP11":comp["escape_angle_deg"]=270.
    for key in ("dc_routing_validation","rf_routing_validation","dc_routed_jobs","rf_routed_jobs","routed_jobs","unrouted_jobs","arcs","shield_vias","ground_regions","mask_regions","routing_sources","routing_complete","dynamic_zif_assignment"):
        p.pop(key,None)
    apply_contact_pool(p,source_hash)
    p["routing_complete"]=False;p["status"]="CORRIDOR_PLACEMENT_READY_FOR_RF_DC_ROUTING"
    if "corridor_placement_revision" in p:
        p.setdefault("previous_corridor_placement_revisions",[]).append(p["corridor_placement_revision"])
    p["corridor_placement_revision"]=dict(source=str(SOURCE),source_sha256=source_hash,target_components=TARGETS,
        SMP11_escape_deg=270,SMP30_escape_deg=90,identity_RF_mapping=True,old_routes_removed=True)
    report=audit(p,old);p["placement_validation"]=report
    assert report["passed"],report["failures"]
    DEST.write_text(json.dumps(p,indent=2));report=copy.deepcopy(report)
    report.update(candidate=str(DEST),candidate_sha256=hashlib.sha256(DEST.read_bytes()).hexdigest(),source_sha256=source_hash)
    audit_path=DEST.with_name(DEST.name.replace("_candidate.json","_audit.json"))
    audit_path.write_text(json.dumps(report,indent=2));assert SOURCE.read_bytes()==raw
    print(json.dumps(report,indent=2))


if __name__=="__main__":main()
